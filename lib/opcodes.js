const OpcodeNames = {};
for (const [name, code] of Object.entries(Opcode)) {
  // для логов — имя из официального клиента (первое объявленное)
  if (!(code in OpcodeNames)) OpcodeNames[code] = name;
}

function getOpcodeName(code) {
  return OpcodeNames[code] || `UNKNOWN_${code}`;
}

